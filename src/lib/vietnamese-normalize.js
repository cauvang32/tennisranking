/** Pre-built character class for the regex (covers all accented Vietnamese chars). */
const accentPattern = /[àáảãạăằắẳẵặèéẻẽêềểễệìíỉĩòóỏõôồốổỗơờởỡờỳýỷỹđÀÁẢÃẠĂẰẮẲẴẶÈÉẺẼÊỀỂỄỆÌÍỈĨÒÓỎÕÔỒỐỔỖỜỞỠỜỲÝỶỸĐ]/g

/** Normalize Vietnamese text by removing accents.
 *  Used by fuzzyMatchPlayer and mapTeamToPlayerPair for name matching.
 *  @param {string} text
 *  @returns {string} accent-stripped text
 */
export function normalizeText(text) {
  if (!text) return ''
  return text.replace(accentPattern, m => ACCENT_MAP[m] || m)
}
